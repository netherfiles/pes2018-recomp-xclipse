#!/usr/bin/env python3
"""Guard the allocator's free-list link dereferences in the generated C++.

The title's allocator keeps its free lists in guest memory: a block's links are
read out of the block and then dereferenced as pointers. A word there that is not
a block address becomes a load from base + that word -- outside the 4 GiB guest
space, where nothing catches it. The replay-goal crash is exactly that: the word
at 12(block) holds 0xFFFFFFFF, is read back as a pointer and dereferenced at
0(r10).

Both shapes below are in sub_82438F58 and in the copy its predecessor's over-long
bound left in sub_82438F50 (ppc_recomp.3.cpp), so the script matches the emitted
code rather than a line number -- ppc/ is regenerated by build.sh on every pass
and the lines move.

  walk    loc: cmplw head,node / beq out / lhz size,-8(node)   the bin walk
  unlink  lwz fd,8(block) / lwz bk,12(block) / lwz .,4(fd)     the unlink check

For each: the links are handed to pes17_heaplink_ok (runtime/kernel/heaplink.h,
the heap the title allocates from, 8-byte aligned) before anything is read or
written through them; a refused link is reported through pes17_heaplink_broken
and the allocator takes the path it takes when a backlink does not answer -- the
unlink or merge is skipped, the block stays where it is. A refused walk pointer
ends the walk, which is the path taken when no block of that size is left, and
the block is inserted at the list head as that path does. Nothing is deleted, so
a patch over a patch is the same file; the run is idempotent.

Drift must fail the build: the patterns are asserted (at least one of each, and
the branch targets must name the label they jump to), so a recompiler or profile
change that stops emitting this code stops the build at this script instead of
shipping the crash again.

usage: fix_heaplinks.py <ppc-dir>
"""
import glob
import os
import re
import sys

MARK = 'pes17-fix_heaplinks'   # in every inserted comment: how a second run sees its own work
# The first line of each guard. A guarded site no longer matches the emitted
# shape (the guard sits between the branch and the dereference), so a second run
# counts these instead: a patched file is a file with nothing left to insert.
WALK_MARK = f"\t// {MARK}: the walk's next pointer came from guest memory"
UNLINK_MARK = f"\t// {MARK}: the block's links were read from guest memory"

INCLUDE_ANCHOR = '#include "ppc_recomp_shared.h"\n'
INCLUDE_LINE = '#include "../runtime/kernel/heaplink.h"  // pes17-fix_heaplinks: refused free-list links\n'

WALK = re.compile(
    r"\t// cmplw cr6,r(?P<a>\d+),r(?P<b>\d+)\n"
    r"\tcr6\.compare<uint32_t>\(ctx\.r(?P=a)\.u32, ctx\.r(?P=b)\.u32, xer\);\n"
    r"\t// beq cr6,0x(?P<target>[0-9A-Fa-f]+)\n"
    r"\tif \(cr6\.eq\) goto loc_(?P<label>[0-9A-F]+);\n"
    r"(?=\t// lhz r(?P<size>\d+),-8\(r(?P<node>\d+)\)\n)")

UNLINK = re.compile(
    r"\t// addi r(?P<link>\d+),r(?P<block>\d+),8\n"
    r"\tctx\.r(?P=link)\.s64 = ctx\.r(?P=block)\.s64 \+ 8;\n"
    r"\t// lwz r(?P<fd>\d+),8\(r(?P=block)\)\n"
    r"\tctx\.r(?P=fd)\.u64 = PPC_LOAD_U32\(ctx\.r(?P=block)\.u32 \+ 8\);\n"
    r"\t// lwz r(?P<bk>\d+),12\(r(?P=block)\)\n"
    r"\tctx\.r(?P=bk)\.u64 = PPC_LOAD_U32\(ctx\.r(?P=block)\.u32 \+ 12\);\n"
    # Everything from the first dereference to the branch a failed check takes,
    # so the label the guard jumps to is this unlink's own.
    r"(?P<anchor>\t// lwz r(?P<f>\d+),4\(r(?P=fd)\)\n"
    r"\tctx\.r(?P=f)\.u64 = PPC_LOAD_U32\(ctx\.r(?P=fd)\.u32 \+ 4\);\n"
    r"\t// lwz r(?P<b>\d+),0\(r(?P=bk)\)\n"
    r"\tctx\.r(?P=b)\.u64 = PPC_LOAD_U32\(ctx\.r(?P=bk)\.u32 \+ 0\);\n"
    r"\t// cmplw cr6,r(?P=b),r(?P=f)\n"
    r"\tcr6\.compare<uint32_t>\(ctx\.r(?P=b)\.u32, ctx\.r(?P=f)\.u32, xer\);\n"
    r"\t// bne cr6,0x(?P<target>[0-9A-Fa-f]+)\n"
    r"\tif \(!cr6\.eq\) goto loc_(?P<label>[0-9A-F]+);\n)")


def walk_guard(node, head, target):
    return (
        f"{WALK_MARK} and may not be a\n"
        f"\t// block; reported, and the list is treated as ended here -- the path the\n"
        f"\t// allocator takes when no block of this size is left.\n"
        f"\tif (!pes17_heaplink_ok(ctx.r{node}.u32))\n"
        f"\t{{\n"
        f"\t\tpes17_heaplink_broken(0u, ctx.r{node}.u32, 0u);\n"
        f"\t\tctx.r{node}.u64 = ctx.r{head}.u64;\n"
        f"\t\tgoto loc_{target};\n"
        f"\t}}\n")


def unlink_guard(block, fd, bk, target):
    # The list is threaded at block+8 (the size word at block+0), and the
    # neighbours' backlinks must name that address: the same test the emitted
    # code makes, reported instead of silent, and made before the dereference.
    node = f"r{block}"
    return (
        f"{UNLINK_MARK}; a link that is\n"
        f"\t// not a heap block is not dereferenced. The unlink is skipped -- the path\n"
        f"\t// the allocator takes when a backlink does not answer -- and reported.\n"
        f"\tif (!pes17_heaplink_ok(ctx.r{fd}.u32) || !pes17_heaplink_ok(ctx.r{bk}.u32) ||\n"
        f"\t    PPC_LOAD_U32(ctx.r{fd}.u32 + 4) != ctx.{node}.u32 + 8 ||"
        f" PPC_LOAD_U32(ctx.r{bk}.u32 + 0) != ctx.{node}.u32 + 8)\n"
        f"\t{{\n"
        f"\t\tpes17_heaplink_broken(ctx.{node}.u32 + 8,"
        f" pes17_heaplink_ok(ctx.r{fd}.u32) ? ctx.r{bk}.u32 : ctx.r{fd}.u32,\n"
        f"\t\t                      uint32_t(PPC_LOAD_U16(ctx.{node}.u32)));\n"
        f"\t\tgoto loc_{target};\n"
        f"\t}}\n")


def patch_file(path, counts):
    with open(path, encoding="utf-8", newline="") as handle:
        source = handle.read()
    edits = []

    for site in UNLINK.finditer(source):
        if site.group('target').upper() != site.group('label'):
            sys.exit(f"{path}: bne 0x{site.group('target')} names loc_{site.group('label')}"
                     " -- the emitted shape changed")
        edits.append((site.start('anchor'), unlink_guard(site.group('block'), site.group('fd'),
                                                         site.group('bk'), site.group('label'))))
        counts['unlink'] += 1

    for site in WALK.finditer(source):
        if site.group('target').upper() != site.group('label'):
            sys.exit(f"{path}: beq 0x{site.group('target')} names loc_{site.group('label')}"
                     " -- the emitted shape changed")
        node, a, b = site.group('node'), site.group('a'), site.group('b')
        if node not in (a, b) or a == b:
            sys.exit(f"{path}: walk at byte {site.start()} does not compare node r{node}"
                     " with the head -- the emitted shape changed")
        head = b if a == node else a
        edits.append((site.end(), walk_guard(node, head, site.group('label'))))
        counts['walk'] += 1

    # Sites guarded by an earlier run: the shape is gone from them, the guard is not.
    counts['unlink'] += source.count(UNLINK_MARK)
    counts['walk'] += source.count(WALK_MARK)

    if not edits:
        return 0
    if INCLUDE_LINE not in source:
        if INCLUDE_ANCHOR not in source:
            sys.exit(f"{path}: no {INCLUDE_ANCHOR.strip()} to hang the guard's include on")
        edits.append((len(INCLUDE_ANCHOR), INCLUDE_LINE))
    for pos, text in sorted(edits, reverse=True):
        source = source[:pos] + text + source[pos:]
    with open(path, "w", encoding="utf-8", newline="") as handle:
        handle.write(source)
    return len(edits)


def main(argv):
    if len(argv) != 2:
        sys.exit(__doc__.strip().splitlines()[-1])
    ppc = argv[1]
    paths = sorted(glob.glob(os.path.join(ppc, "ppc_recomp.*.cpp")))
    if not paths:
        sys.exit(f"{ppc}: no ppc_recomp.*.cpp -- run the recompiler first")

    counts = {'walk': 0, 'unlink': 0}
    for path in paths:
        changed = patch_file(path, counts)
        if changed:
            print(f"  {os.path.basename(path)}: {changed} insert(s)", file=sys.stderr)

    print(f"heaplinks: {counts['unlink']} unlink and {counts['walk']} walk site(s) guarded", file=sys.stderr)
    # Drift, or a tree the allocator is no longer in: fail rather than ship it.
    if counts['unlink'] == 0 or counts['walk'] == 0:
        print("heaplinks: the allocator's free-list code was not found -- fix this script"
              " before the build goes on", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
